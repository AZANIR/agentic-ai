"""Єдине джерело часу в конвеєрі — і причина, з якої перевірки етапу не мигтять.

**Годинник подається параметром і ніде не читається з системного.** Етап 5 ухвалив це саме
рішення заради детермінізму TTL; тут воно потрібне з іншої причини, сильнішої:

> Перевірка, що міряє час справжнім годинником, залежить від навантаження машини. Вона
> проходить девʼять разів і падає десятий. Це найгірший вид перевірки — її **вимикають**, а
> разом із нею зникає єдиний доказ головної тези етапу.

**Підроблений годинник не спить.** `sleep(200)` рухає лічильник на 200 і повертає керування
негайно. Прогін, що «займає» півтори секунди, виконується за мілісекунди — тож вимога «нуль
мигтінь із двадцяти прогонів» коштує нуль.

**Чому не широкі допуски.** Найпростіша альтернатива — справжній годинник і `assert x < 3000`.
Допуск, широкий настільки, щоб не мигтіти на завантаженій машині, **вже не розрізняє** батч і
стрімінг: обидва вкладаються. Перевірка перестає доводити те, заради чого написана.

**Чому не мок `time.perf_counter`.** Мок привʼязується до того, **де саме** код кличе годинник.
Перенеси виклик на рядок вище — і мок промахнеться, а перевірка мовчки перестане міряти.
"""

from __future__ import annotations

import time
from typing import Protocol


class Clock(Protocol):
    """Годинник конвеєра. Обидві реалізації живуть за цим інтерфейсом."""

    name: str

    def now(self) -> float:
        """Поточний момент у **мілісекундах**. Одиниця одна на весь етап — навмисно."""
        ...

    def sleep(self, millis: float) -> None:
        """Зачекати вказану кількість мілісекунд."""
        ...


class FakeClock:
    """Годинник, що рухається лише тоді, коли його про це просять.

    Стан — одне число. Тому той самий сценарій дає те саме число на будь-якій машині, у
    будь-який час доби й під будь-яким навантаженням.
    """

    name = "fake"

    def __init__(self, start: float = 0.0) -> None:
        self._now = start
        # Скільки разів і на скільки просили зачекати. Потрібне не для звіту, а для
        # перевірки: «конвеєр не викликав синтезу» доводиться відсутністю його затримки.
        self.waits: list[float] = []

    def now(self) -> float:
        return self._now

    def sleep(self, millis: float) -> None:
        if millis < 0:
            raise ValueError(f"відʼємна затримка {millis} — це не очікування, а помилка")
        self.waits.append(millis)
        self._now += millis


class RealClock:
    """Справжній годинник. Живий режим бере його тим самим інтерфейсом."""

    name = "real"

    def now(self) -> float:
        return time.perf_counter() * 1000.0

    def sleep(self, millis: float) -> None:
        time.sleep(millis / 1000.0)


def get_clock(*, real: bool = False) -> Clock:
    """Годинник за режимом. Дефолт — підроблений: етап проходиться без очікування."""
    return RealClock() if real else FakeClock()
