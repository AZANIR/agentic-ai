"""Підроблена модель — одна на весь етап, з **детермінованим** розкидом затримок.

Раніше цей код існував у трьох копіях: у демо, у перевірках і в розвʼязку вправи. Копії
розійшлися б за першої ж правки, а етап, теза якого «два числа на однакових даних», не має
права міряти двома різними моделями.

**Чому затримка — функція номера прогону.** AC-04 вимагає сто прогонів «із розкидом
затримок». Підроблений годинник розкиду не дає за побудовою: ті самі дані завжди дають те
саме число — і це його головна чеснота (ADR-0002). Тому розкид вносить **модель**, а не
годинник: `latency(run)` — чиста функція індексу, тож сто прогонів дають сто справжніх
вимірів, і повторний прогін набору дає ті самі сто.

Перша редакція розкиду не мала взагалі: розподіл набирався літералами
`[400.0] * 90 + [1600.0] * 10`, і демо друкувало «прогонів: 100» для списку, набраного
руками. На етапі, теза якого «оптимізувати можна лише те, що виміряно», це найгірше з
можливих місць для вигаданого числа.

**Чому затримка — не стан обʼєкта.** Лічильник усередині моделі означав би, що результат
залежить від того, скільки разів її вже кликали, — тобто рівно та вада, від якої етап 6
має цілий урок. Номер прогону передається явно.
"""

from __future__ import annotations

from collections.abc import Iterator
from typing import Any

from stages.s07_voice.clock import Clock

ANSWER = "Замовлення в дорозі. Очікуйте доставку завтра до вечора."
CHUNKS = ("Замовлення в дорозі.", " Очікуйте доставку", " завтра до вечора.")

# Затримки навмисно РІЗНІ між кроками: інакше «найдорожчий крок» стає жеребкуванням між
# рівними, і питання «що оптимізувати першим» лишається без відповіді.
THINK_MILLIS = 750.0

# Хвіст **двоярусний**: кожен десятий прогін учетверо повільніший, кожен пʼятдесятий —
# увосьмеро. Це не песимізм, а типова форма розподілу для будь-чого, що ходить у мережу.
# Один ярус дав би p95, що дорівнює найгіршому, — і різниця між «майже найгірший» і
# «найгірший» зникла б саме там, де етап її показує.
SLOW_EVERY = 10
SLOW_FACTOR = 4.0
WORST_EVERY = 50
WORST_FACTOR = 8.0


def latency(run: int = 0, *, base: float = THINK_MILLIS) -> float:
    """Скільки думає модель на прогоні номер `run`. Чиста функція індексу.

    `run=0` — звичайний прогін: саме його бачать перевірки двох чисел, тож головні числа
    етапу від хвоста не залежать.
    """
    if WORST_EVERY and run % WORST_EVERY == WORST_EVERY - 1:
        return base * WORST_FACTOR
    if SLOW_EVERY and run % SLOW_EVERY == SLOW_EVERY - 1:
        return base * SLOW_FACTOR
    return base


def whole(*, run: int = 0) -> Any:
    """Модель, що пише всю відповідь одразу. Для батчевого конвеєра."""

    def think(_: str, *, clock: Clock) -> str:
        clock.sleep(latency(run))
        return ANSWER

    return think


def in_chunks(*, run: int = 0) -> Any:
    """Та сама модель, але фрагментами. **Сума затримок однакова** — це навмисно.

    Інакше стрімінг виглядав би швидшим тому, що йому дали менше роботи, і число нічого б
    не доводило.
    """

    def think_chunks(_: str, *, clock: Clock) -> Iterator[str]:
        for chunk in CHUNKS:
            clock.sleep(latency(run) / len(CHUNKS))
            yield chunk

    return think_chunks


def silent_model(*, run: int = 0) -> Any:
    """Модель, що не віддала нічого. Режим відмови, а не крайній випадок.

    Порожній стрім лишає `first_audio` непозначеним, і конвеєр мусить сказати це прямо, а
    не показати нуль — найкраще можливе число для прогону, у якому звуку не було.
    """

    def think_chunks(_: str, *, clock: Clock) -> Iterator[str]:
        clock.sleep(latency(run))
        return
        yield ""  # noqa: B901 — робить функцію генератором, не виконується

    return think_chunks
