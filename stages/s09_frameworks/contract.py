"""Контракт задачі: те, що спільне для всіх реалізацій — і **виконуване** (ADR-0001).

Порівняння фреймворків має сенс лише тоді, коли задача та сама. Найпростіше зафіксувати це
прозою — і саме тому майже всі порівняння фреймворків міряють вправність автора, а не
фреймворки.

Проблема не в недобросовісності, а в непомітності. Реалізація на CrewAI природно хоче ще один
крок делегування, реалізація на LangGraph — окремий вузол валідації. Кожне таке відхилення
виглядає як «так тут прийнято», і кожне робить чужу колонку неспівмірною.

Тому контракт — це код. П'ять елементів, і **шлях** серед них:

    вхід             те саме питання
    інструменти      рівно `search_notes`, рівно один виклик
    модель           клієнт подається ззовні, і його бачив лічильник
    умова зупинки    відповідь дано, а не обірвано на півдорозі
    форма            відповідь спирається на видані нотатки

Константи бюджету кроків тут немає навмисно: жодна реалізація його не рахує, а константа,
яку ніхто не читає, у навчальному репозиторії дорожча за звичайну — читач шукає, де вона
працює, і не знаходить.

Кількість викликів моделі контрактом **не** обмежена: це вимірювана колонка, а не порушення.
Обмежити її означало б оголосити фреймворк зламаним за те, що він фреймворк.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from shared.fake_llm import text, tool_call

QUESTION = "Скільки днів на повернення товару в NovaShop і що для цього потрібно?"

# Єдина нотатка, яку віддає єдиний інструмент. Належить контракту: усі чотири реалізації
# отримують той самий текст, інакше різниця в токенах міряла б різні дані.
NOTE = (
    "Повернення приймається протягом чотирнадцяти днів від отримання. "
    "Потрібен чек і оригінальна упаковка."
)

ANSWER = (
    "Повернути товар можна протягом чотирнадцяти днів від отримання; "
    "знадобиться чек і оригінальна упаковка."
)

TOOL = "search_notes"
TOOLS = (TOOL,)

# Основи слів, які відповідь мусить згадати. Основи, а не слова: українська відмінює, і
# точний збіг дав би нуль там, де людина бачить збіг (той самий урок, що на етапі 5).
GROUNDING = ("чотирнадцят", "чек", "упаковк")

ANSWERED = "answered"
OUT_OF_BUDGET = "out_of_budget"

RESEARCH_PROMPT = (
    f"Ти помічник підтримки NovaShop. Питання клієнта: {QUESTION}\n"
    f"Знайди потрібне у базі знань інструментом {TOOL}."
)
WRITER_PROMPT = (
    f"Питання клієнта: {QUESTION}\n"
    "Нотатки з бази знань: {note}\n"
    "Напиши коротку відповідь, спираючись ЛИШЕ на нотатки."
)

TOOL_SCHEMA: dict[str, Any] = {
    "type": "function",
    "function": {
        "name": TOOL,
        "description": "Знайти нотатки в базі знань NovaShop",
        "parameters": {
            "type": "object",
            "properties": {"query": {"type": "string"}},
            "required": ["query"],
        },
    },
}


def search_notes(query: str) -> str:
    """Єдиний інструмент задачі. Відповідь стала: інструмент — частина контракту, не змінна."""
    return NOTE


def owned_texts() -> frozenset[str]:
    """Тексти, які **контракт** відправляє до моделі.

    Усе, що поїхало понад цей перелік, додав фреймворк — і саме це рахує `counters.py`.
    Перелік живе тут, а не в лічильнику: інакше додати рядок до промпту й «випадково»
    зробити його безкоштовним було б однією правкою в чужому файлі.
    """
    return frozenset(
        {
            RESEARCH_PROMPT,
            WRITER_PROMPT.format(note=NOTE),
            NOTE,
            QUESTION,
            TOOL_SCHEMA["function"]["description"],
        }
    )


def script() -> list[dict[str, Any]]:
    """Сценарій підробленої моделі — **спільний** для всіх реалізацій.

    Різні сценарії зробили б токени неспівмірними ще до того, як фреймворк щось додав.
    `repeat_last` лишає останній крок доступним: реалізація, що кличе модель зайвий раз,
    отримує ту саму відповідь, а зайвий виклик стає числом у колонці, не помилкою.
    """
    return [tool_call(TOOL, {"query": "повернення товару"}), text(ANSWER)]


@dataclass(frozen=True)
class Result:
    """Що реалізація зробила. Порівнюється не текст, а виконання контракту."""

    name: str
    asked: str
    answer: str
    tools_used: tuple[str, ...]
    stopped_by: str
    model_calls: int
    coordination: str
    why_source: str
    steps: tuple[str, ...] = field(default_factory=tuple)


def violations(result: Result) -> tuple[str, ...]:
    """Які елементи контракту порушено. Порожньо — реалізація порівнянна з іншими.

    Порушник не викидається з таблиці й не виправляється: його рядок лишається, але **без
    чисел**, із назвою порушеного елемента. Мовчазне включення дало б число, яке виглядає
    порівнянним і не є ним.
    """
    broken = []
    if result.asked != QUESTION:
        broken.append("вхід: питання не те, що в контракті")
    if result.tools_used != TOOLS:
        broken.append(f"інструменти: {list(result.tools_used)} замість {list(TOOLS)}")
    if result.model_calls < 1:
        broken.append("модель: жодного виклику — реалізація не питала модель")
    if result.stopped_by != ANSWERED:
        broken.append(f"умова зупинки: {result.stopped_by!r} замість {ANSWERED!r}")
    if not result.answer.strip():
        broken.append("форма: відповідь порожня")
    else:
        missing = [stem for stem in GROUNDING if stem not in result.answer.lower()]
        if missing:
            broken.append(f"форма: відповідь не спирається на нотатки — немає {missing}")
    return tuple(broken)
