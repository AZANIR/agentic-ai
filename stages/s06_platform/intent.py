"""Класифікатор наміру: одна гілка за один виклик моделі.

Етап 3 дав робочий supervisor — маршрут, передача спеціалістові, оцінка відповіді, цикл
ревізій. Він коштує **щонайменше два** виклики на запит, і кожне коло ревізії додає ще два.

Сервіс етапу 6 має обрати одну з трьох гілок і віддати відповідь користувачеві. Оцінювати її
нікому: цикл ревізій має сенс там, де є кому переоцінювати, а тут результат іде назовні. Тому
класифікація — один виклик (ADR-0001).

**Межа названа числом, а не думкою.** Класифікатор помиляється на **складених** запитах — тих,
що стосуються двох гілок одночасно:

    «поверніть гроші за ord_4471 — і скільки днів це триває»
     ^^^^^^^^^^^^^^^^^^^^^^^^^^     ^^^^^^^^^^^^^^^^^^^^^^^
     orders                          knowledge

Supervisor такий запит розклав би на дві передачі. Класифікатор обере одну гілку, і друга
половина питання лишиться без відповіді. Частка таких запитів заміряна на наборі `MIXED` —
див. перевірку етапу; урок називає це число, а не переказує словами.

**Вичерпаний бюджет не вмикає запасного шляху.** Спокуса очевидна: класифікувати за
ключовими словами й відповісти хоч якось. Вона відхилена в ADR-0001 — запобіжник, який у
цьому стані **відповідає**, робить відмову м'якою рівно там, де вона має бути жорсткою.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from shared.llm import get_model

ORDERS = "orders"
KNOWLEDGE = "knowledge"
MATH = "math"
BRANCHES = (ORDERS, KNOWLEDGE, MATH)

_PROMPT = """Ти класифікуєш запит покупця інтернет-магазину в рівно одну категорію.

    orders     конкретне замовлення: статус, повернення, доставка за номером
    knowledge  правила й політики магазину: терміни, умови, склад товару
    math       обчислення: скільки разом, яка знижка, порахуй

Відповідай **одним словом** із переліку вище й нічим більше.

Запит: {question}"""


@dataclass(frozen=True)
class Intent:
    """Обрана гілка й те, чим її обрано. `certain` — чи відповідь моделі впізнано."""

    branch: str
    certain: bool
    said: str

    def as_step(self) -> dict[str, Any]:
        """Крок трейсу. Гілка потрапляє у трейс **першою** — до будь-якої роботи."""
        return {"branch": self.branch, "certain": self.certain, "model_said": self.said}


def classify(question: str, *, client: Any, model: str | None = None) -> Intent:
    """Одна гілка за один виклик. Невпізнана відповідь — не виняток, а `knowledge`.

    Чому саме `knowledge` як запасна гілка: вона єдина не потребує ні номера замовлення, ні
    чисел, тобто єдина, що не зламається на довільному запиті. Гілка за замовчуванням має
    бути найбезпечнішою, а не найчастішою.
    """
    reply = client.chat.completions.create(
        model=model or get_model(),
        messages=[{"role": "user", "content": _PROMPT.format(question=question)}],
    )
    said = (reply.choices[0].message.content or "").strip().lower()

    # Модель схильна дописувати крапку, лапки й пояснення. Шукаємо назву гілки у сказаному,
    # а не вимагаємо точної рівності: вимога дослівності перетворює будь-яку багатослівність
    # на відмову, і читач бачить «класифікатор не працює» там, де він працює.
    for branch in BRANCHES:
        if branch in said:
            return Intent(branch=branch, certain=True, said=said)
    return Intent(branch=KNOWLEDGE, certain=False, said=said)
