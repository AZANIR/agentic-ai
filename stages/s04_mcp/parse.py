"""Дістати дані з відповіді сервера, у якій довкола них є текст.

Відповідь MCP-сервера — це **текст**. У нього можуть входити дані, а можуть — дані разом із
прозою: поясненням, попередженням, нагадуванням про інший інструмент. Це не вада конкретного
сервера, а властивість формату: сервер має право говорити.

Три способи це розібрати, і два з них ламаються по-різному:

    json.loads(усе)      падає на першому ж сервері, який привітався
    регулярка по тексту  знаходить ЩОСЬ майже завжди
    виділений блок       межа однозначна

Середній варіант вартий окремої уваги, бо виглядає найпрактичнішим. У прозі трапляються
фігурні дужки; у поясненні трапляється приклад формату. Парсер, який бере перше схоже на JSON,
одного дня візьме приклад із документації замість даних — **і не скаже про це нічого**. Саме
цей випадок перевіряється окремо.

**Відсутність блоку — це стан, а не порожнеча.** «Сервер нічого не повернув» і «сервер
повернув порожній перелік» — різні події з різними причинами, і зливати їх означає втратити
половину діагностики. Перше кидає `NoPayload` із текстом сервера всередині; друге повертає
`[]`, бо це і є відповідь.
"""

from __future__ import annotations

import json
import re
from typing import Any

# Блок, огороджений трьома зворотними лапками. Позначка мови необов'язкова: сервери пишуть
# і ```json, і просто ```.
_FENCED = re.compile(r"```(?:json)?\s*\n(.*?)\n```", re.S)


class NoPayload(Exception):
    """Сервер відповів, але даних у відповіді немає. Не те саме, що порожній результат."""


def extract_payload(response: str) -> Any:
    """Повернути дані з відповіді. Текст навколо ігнорується.

    :raises NoPayload: якщо блоку з даними немає взагалі. Текст сервера йде в повідомлення —
        без нього не лишається нічого, за чим можна зрозуміти, що сталось.
    """
    stripped = response.strip()

    # Найпростіший випадок: сервер мовчазний і відповів самими даними.
    if stripped.startswith(("{", "[")):
        try:
            return json.loads(stripped)
        except json.JSONDecodeError:
            pass

    for block in _FENCED.findall(response):
        try:
            return json.loads(block.strip())
        except json.JSONDecodeError:
            continue

    raise NoPayload(_first_lines(stripped))


def _first_lines(text: str, limit: int = 2) -> str:
    """Початок відповіді сервера — те єдине, що лишається для діагностики."""
    lines = [line.strip() for line in text.splitlines() if line.strip()]
    return " ".join(lines[:limit]) or "(порожня відповідь)"


def describe_failure(error: Exception, *, phase: str) -> dict[str, str]:
    """Відмова у вигляді, придатному для стану й трейсу.

    Фаза важливіша за текст винятку. «Сервер не запустився», «замовк посеред виклику» і
    «відповів, але розібрати нічого» — три різні події, які з тексту помилки часто
    невідрізненні, а виправляються по-різному.
    """
    return {"phase": phase, "reason": str(error)}
