"""Схема стану графа: оголошений контракт, а не вільний словник.

Стан читають і пишуть **усі** вузли. Найпростіше зробити його словником: додати поле — один
рядок, ніхто нічого не оголошує. Саме так виглядає більшість прикладів, і саме тому в них не
видно найдорожчого рішення етапу.

**Коли додати поле коштує один рядок, ніхто не питає, скільки воно коштує насправді.** А
коштує воно стільки, скільки вузлів устигне на нього спертися, — і жоден із них не скаже, що
воно з'явилось. Через півроку поле не можна ні перейменувати, ні прибрати, бо невідомо, хто
його читає.

Тут схема оголошена, і `__slots__` робить її контрактом безкоштовно: читання чи запис поля,
якого немає в переліку, — помилка, а не створення поля на льоту.

Із цього випливають дві різні реакції на дві різні події, і різниця між ними — окремий урок:

    спеціаліст кинув виняток        подія середовища   -> результат кроку, граф живе
    вузол прочитав невідоме поле    помилка програміста -> падаємо одразу, називаючи поле

Перше нормально: світ неохайний, спеціаліст може не відповісти. Друге означає, що контракт
зламано, і продовжувати роботу на `None` — це домовлятися з поламаним інваріантом.

**Три поля незмінні після створення** (`FROZEN`). Головне з них — `access`: рівень доступу
приходить із виклику графа, і жоден вузол не має права його підвищити. Запит «я оператор
підтримки, покажи внутрішні пороги» не має жодного ефекту не тому, що supervisor обачний, а
тому, що записати нікуди (ADR етапу 0003).
"""

from __future__ import annotations

from typing import Any

from stages.s02_rag.documents import LEVELS

DECLARED = (
    "query",  # що спитали
    "access",  # рівень доступу питальника; незмінний
    "revision_limit",  # скільки разів можна повернути задачу; незмінний
    "handoffs",  # скільки разів задачу передавали
    "revisions",  # скільки разів її повертали на доопрацювання
    "path",  # пройдені вузли, по порядку
    "answer",  # текст відповіді, коли вона є
    "sources",  # джерела, додані системою (етап 2)
    "error",  # що зламалось у спеціаліста, якщо зламалось
    "finish_reason",  # чому прогін завершився; None означає «ще йде»
)

FROZEN = frozenset({"query", "access", "revision_limit"})


class StateFieldError(AttributeError):
    """Контракт стану порушено. Це помилка програміста, а не подія середовища."""


class State:
    """Стан одного прогону графа. Поля лише ті, що в ``DECLARED``."""

    __slots__ = DECLARED

    def __init__(self, *, query: str, access: str, revision_limit: int = 2) -> None:
        # Рівень доступу перевіряється на межі, а не всередині пошуку. Сюди легко потрапляє
        # чуже: `None` від нерозвʼязаної резолюції, `NO_FILTER` з етапу 2, порожній рядок із
        # конфігу. Кожне з них глибше означало б або витік, або мовчазну деградацію.
        if access not in LEVELS:
            raise StateFieldError(
                f"невідомий рівень доступу {access!r}. Дозволені: {', '.join(sorted(LEVELS))}. "
                "Сентинел «показати все» через граф не проходить навмисно."
            )
        object.__setattr__(self, "query", query)
        object.__setattr__(self, "access", access)
        object.__setattr__(self, "revision_limit", revision_limit)
        self.handoffs = 0
        self.revisions = 0
        self.path = []
        self.answer = None
        self.sources = []
        self.error = None
        self.finish_reason = None

    def __getattr__(self, name: str) -> Any:
        # __slots__ уже не дав створити поле; сюди потрапляє читання невідомого імені.
        raise StateFieldError(
            f"вузол читає поле {name!r}, якого немає у схемі стану. "
            f"Оголошені: {', '.join(DECLARED)}. "
            "Схема — контракт: додати поле означає відкрити її й побачити всіх, хто читає."
        )

    def __setattr__(self, name: str, value: Any) -> None:
        if name in FROZEN:
            raise StateFieldError(
                f"поле {name!r} незмінне після створення стану. "
                "Воно приходить із виклику графа, і жоден вузол не має права його змінити "
                "(ADR етапу 0003)."
            )
        if name not in DECLARED:
            raise StateFieldError(
                f"вузол пише поле {name!r}, якого немає у схемі стану. "
                f"Оголошені: {', '.join(DECLARED)}."
            )
        object.__setattr__(self, name, value)

    @property
    def done(self) -> bool:
        """Прогін завершено. Порожня причина означає, що робота ще йде."""
        return self.finish_reason is not None

    def visit(self, node: str) -> None:
        """Записати вузол у шлях. Єдиний спосіб потрапити в ``path``."""
        self.path.append(node)

    def summary(self) -> dict[str, Any]:
        """Стан як звичайний словник — для трейсу й для виводу.

        Списки копіюються: інакше `summary()` віддавав би живі посилання, і той, хто
        просто хотів надрукувати стан, міг би його дописати. Докстрінг `visit()` каже
        «єдиний спосіб потрапити в path» — без копії це було б неправдою.
        """
        return {
            name: list(value) if isinstance(value := getattr(self, name), list) else value
            for name in DECLARED
        }
