-- Тут навмисно немає прикладних таблиць. Кожна таблиця приходить разом з етапом,
-- якому вона потрібна: пам'ять — з етапу 5, замовлення — з етапу 6. Схема, створена
-- «наперед, про всяк випадок», застаріває швидше, ніж її встигають використати.
--
-- Розширення vector дає тип vector(N) і оператор <=> (косинусна відстань) —
-- саме те, що на етапі 2 робиться руками на NumPy, а в проді робить БД (ADR-0004).

